    """在同一个事务中：标记请求为已接受 + 创建双向好友记录"""
    now = datetime.now(timezone.utc)

    req.status = "ACCEPTED"
    req.handled_at = now

    # 创建双向好友记录
    friend1 = MsgFriend(
        account_type=req.applicant_type,
        account_id=req.applicant_id,
        friend_account_type=req.recipient_type,
        friend_account_id=req.recipient_id,
        remark=req.message[:64] if req.message else None,
        status="ACTIVE",
        friend_at=now,
    )
    friend2 = MsgFriend(
        account_type=req.recipient_type,
        account_id=req.recipient_id,
        friend_account_type=req.applicant_type,
        friend_account_id=req.applicant_id,
        status="ACTIVE",
        friend_at=now,
    )
    repo.db.add(friend1)
    repo.db.add(friend2)
