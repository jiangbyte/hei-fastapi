        from app.modules.iam.enums import AccountIdentityType

        keyword = query.keyword
        keyword_like = f"%{keyword}%"
        results: list[SearchUserSchema] = []
        seen: set[tuple[str, str]] = set()

        # 获取我的好友 / 待处理申请，用于标记状态（仍排除自己）
