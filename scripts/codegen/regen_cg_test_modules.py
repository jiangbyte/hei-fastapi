def _disable_test_module(
    files: list[CodegenPreviewFile], module_name: str
) -> list[CodegenPreviewFile]:
    patched: list[CodegenPreviewFile] = []
    for item in files:
        content = item.content
        if (
            item.path.endswith("/module.py")
            or item.path.endswith("\\module.py")
            or Path(item.path).name == "module.py"
        ):
            if "enabled=" not in content:
                content = content.replace(
                    f'    name="{module_name}",\n',
                    f'    name="{module_name}",\n    enabled=False,\n',
                )
        patched.append(CodegenPreviewFile(path=item.path, language=item.language, content=content))
    return patched


def main() -> None:
    written: list[str] = []
    for codegen_plan, main_fields, sub_fields in build_modules():
        module_name = codegen_plan.main_module_path.replace("/", ".")
        files = _disable_test_module(
            render_files(codegen_plan, main_fields, sub_fields), module_name
        )
        result = apply_preview_files(files, ROOT, skip_menu_sql=True)
        written.extend(result.written)
        written.extend(f"MERGED {path}" for path in result.merged)

    for orphan in (
        ROOT / "web/admin/src/views/biz/cg-test-knowledge-category/components/ChildModalDetail.vue",
        ROOT / "web/admin/src/views/biz/cg-test-knowledge-category/components/ChildModalForm.vue",
    ):
        if orphan.exists():
            orphan.unlink()
            written.append(f"DELETED {orphan.relative_to(ROOT)}")

    print(f"touched {len(written)} paths")
    for item in written:
        print(f"  {item}")


if __name__ == "__main__":
    main()
