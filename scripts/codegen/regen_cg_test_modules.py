def field(
    *,
    column_name: str,
    column_comment: str,
    python_type: str,
    db_type: str,
    is_primary_key: bool = False,
    is_nullable: bool = True,
    is_required: bool = False,
    show_in_query: bool = False,
    query_operator: str | None = "LIKE",
    max_length: int | None = 64,
    form_widget: str | None = None,
    dict_code: str | None = None,
    table_role: str = "MAIN",
    sort: int = 10,
    show_in_table: bool = True,
    show_in_form: bool | None = None,
    show_in_detail: bool = True,
) -> SysCodegenField:
    if form_widget is None:
        if python_type == "datetime":
            form_widget = "datetime"
        elif python_type in {"dict", "dict[str, Any]"} or "json" in db_type:
            form_widget = "textarea"
        elif python_type == "bool":
            form_widget = "switch"
        elif python_type in {"int", "float"}:
            form_widget = "number"
        elif "text" in db_type:
            form_widget = "textarea"
        else:
            form_widget = "input"
    if show_in_form is None:
        show_in_form = not is_primary_key and column_name not in AUDIT
    if is_primary_key:
        is_nullable = False
        is_required = True
        show_in_form = False
        show_in_query = False
    if column_name in AUDIT:
        show_in_form = False
        show_in_query = False
        show_in_table = False
    ts_map = {
        "str": "string",
        "int": "number",
        "float": "number",
        "bool": "boolean",
        "datetime": "string",
        "dict": "Record<string, any>",
        "dict[str, Any]": "Record<string, any>",
    }
    return SysCodegenField(
        id=f"{table_role}:{column_name}",
        plan_id="regen",
        table_role=table_role,
        column_name=column_name,
        column_comment=column_comment,
        db_type=db_type,
        python_type="dict" if python_type.startswith("dict") else python_type,
        typescript_type=ts_map.get(python_type, "string"),
        form_widget=form_widget,
        dict_code=dict_code,
        query_operator=query_operator if show_in_query else None,
        show_in_table=show_in_table,
        show_in_form=show_in_form,
        show_in_detail=show_in_detail,
        show_in_query=show_in_query,
        is_primary_key=is_primary_key,
        is_required=is_required,
        is_unique=False,
        is_nullable=is_nullable,
        max_length=max_length,
        sort=sort,
    )


